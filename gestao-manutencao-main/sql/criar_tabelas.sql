
CREATE TABLE EQUIPAMENTO (
    ID_EQUIPAMENTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    MODELO VARCHAR2(100) NOT NULL,
    NUMERO_SERIE VARCHAR2(50) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'DISPONIVEL' NOT NULL,

    CONSTRAINT PK_EQUIPAMENTO
        PRIMARY KEY (ID_EQUIPAMENTO),

    CONSTRAINT UK_EQUIPAMENTO_SERIE
        UNIQUE (NUMERO_SERIE),

    CONSTRAINT CK_EQUIPAMENTO_STATUS
        CHECK (STATUS IN (
            'DISPONIVEL',
            'EM_MANUTENCAO',
            'INATIVO'
        ))
);

CREATE TABLE TECNICO (
    ID_TECNICO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    ESPECIALIDADE VARCHAR2(100) NOT NULL,

    CONSTRAINT PK_TECNICO
        PRIMARY KEY (ID_TECNICO)
);

CREATE TABLE MANUTENCAO (
    ID_MANUTENCAO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_EQUIPAMENTO NUMBER NOT NULL,
    ID_TECNICO NUMBER NOT NULL,
    DATA_MANUTENCAO DATE DEFAULT SYSDATE NOT NULL,
    DESCRICAO VARCHAR2(500) NOT NULL,
    CUSTO NUMBER(10,2) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_MANUTENCAO
        PRIMARY KEY (ID_MANUTENCAO),

    CONSTRAINT FK_MANUT_EQUIPAMENTO
        FOREIGN KEY (ID_EQUIPAMENTO)
        REFERENCES EQUIPAMENTO (ID_EQUIPAMENTO),

    CONSTRAINT FK_MANUT_TECNICO
        FOREIGN KEY (ID_TECNICO)
        REFERENCES TECNICO (ID_TECNICO),

    CONSTRAINT CK_MANUTENCAO_CUSTO
        CHECK (CUSTO >= 0)
);
